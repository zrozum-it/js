// Number
const regularNumber = 123;

console.log(regularNumber);
console.log(typeof regularNumber);
// number


// BigInt
const bigNumber = 123n;

console.log(bigNumber);
console.log(typeof bigNumber);
// bigint


// BigInt can store very large integers
const hugeNumber = 987654321098765432109876543210n;

console.log(hugeNumber);
console.log(typeof hugeNumber);
// bigint